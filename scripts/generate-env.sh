#!/usr/bin/env bash
# =============================================================================
# Generate a local .env with strong random secrets.
#
# Usage:
#   ./scripts/generate-env.sh           # Interactive: refuses to overwrite existing .env
#   ./scripts/generate-env.sh --force   # Overwrite existing .env
#
# Workshop Studio note: this script is for LOCAL docker-compose only.
# In AWS Workshop Studio the CDK stack provisions equivalent secrets in
# AWS Secrets Manager and injects them into ECS tasks at runtime.
# =============================================================================

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${ROOT_DIR}/.env"
FORCE="${1:-}"

if [[ -f "${ENV_FILE}" && "${FORCE}" != "--force" ]]; then
  echo "ERROR: ${ENV_FILE} already exists. Pass --force to overwrite." >&2
  exit 1
fi

rand_b64() {
  # Length 24 bytes -> 32 base64 chars (no padding); URL-safe.
  python3 -c "import secrets; print(secrets.token_urlsafe(${1:-24}))"
}

POSTGRES_PASSWORD="$(rand_b64 24)"
JWT_SECRET="$(rand_b64 48)"
REDIS_PASSWORD="$(rand_b64 24)"

cat > "${ENV_FILE}" <<EOF
# Generated by scripts/generate-env.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
# DO NOT COMMIT THIS FILE.

APP_ENV=local
LOG_LEVEL=INFO

POSTGRES_USER=postgres
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
POSTGRES_DB=loandb
DATABASE_URL=postgresql://postgres:${POSTGRES_PASSWORD}@postgresql:5432/loandb

REDIS_PASSWORD=${REDIS_PASSWORD}
REDIS_URL=redis://:${REDIS_PASSWORD}@redis:6379/0

JWT_SECRET=${JWT_SECRET}
JWT_ALGORITHM=HS256
JWT_ISSUER=loan-management-system
JWT_AUDIENCE=loan-management-api
JWT_ACCESS_TOKEN_EXPIRE_MINUTES=30
JWT_REFRESH_TOKEN_EXPIRE_DAYS=7

CORS_ALLOWED_ORIGINS=http://localhost:8000,http://localhost:5173,http://localhost:3000

ENABLE_DEMO_SEED=true

ALLOW_STRESS_TEST=false
WEBHOOK_URL=
WEBHOOK_SECRET=

AUTO_DEBIT_SUCCESS_RATE=0.9
REMINDER_DAYS=3
OVERDUE_NOTICE_DAYS=7
LEGAL_NOTICE_DAYS=15
EMAIL_SIMULATION=true
EOF

chmod 600 "${ENV_FILE}"

cat <<EOF

✅ Created ${ENV_FILE} with random secrets (mode 0600).

Demo sign-in for the local stack (workshop-only credential, also documented
in README "Sign in with the demo credentials"):
   admin           Admin12345!

Start the stack:  cd infrastructure && docker-compose up --build
EOF
